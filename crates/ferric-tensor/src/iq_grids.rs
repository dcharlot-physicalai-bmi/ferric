//! ⛔ This is a SECOND copy. `ferric-gguf` holds the same tables for its CPU decoder, and this
//! crate cannot depend on that one — `ferric-tensor` sits BELOW `ferric-gguf` in the layering, and
//! inverting that just to share a constant would be a worse trade than duplicating it.
//!
//! What makes the duplication safe is that it is GATED, not trusted: a test compares every entry
//! against `ferric-gguf`'s copy (a dev-dependency, so the check costs nothing at build time) and
//! fails if they ever diverge. A duplicated table with a gate is a cache; a duplicated table
//! without one is a second source of truth, and the only difference is whether anything fails when
//! they disagree.
//!
//! IQ2_XXS grid points are 64-bit and WGSL has no `u64`, so each is stored as `(low, high)`:
//! element `i` occupies slots `2i` and `2i+1`, low word first. IQ3_XXS points are already 32-bit.

