#!/usr/bin/env python3
"""Build the linear table behind ferric_core::cpu::det_tanh.

The committed bytes are `crates/ferric-core/src/det_tanh_table.bin`, sha256
`899a6e91ef20ba61eb64222ae98f31bb7c3e12cbda25f0bc8472de621fcf0593`.
`det_tanh_table_matches_the_generator` rebuilds those bytes from `f64::tanh`
and refuses a mismatch. This script is the same procedure:

1. Binary-search the smallest f32 at which `f32(tanh(f64(x)))` is 1.
2. Slot width W = 2^-14. Slot count is floor(sat / W) + 1.
3. Slot i stores little-endian f32 pairs
   anchor = f32(tanh(i*W)), slope = f32((tanh((i+1)*W) - tanh(i*W)) / W).

numpy.tanh and Rust f64::tanh agree on these arguments at f32 rounding.

tanh is odd, so the table stores only x >= 0. Slot i covers
[i / 16384, (i + 1) / 16384). The value is

    anchor + slope * (x - i / 16384)

with anchor and slope stored as f32 and every mul and add rounded on its
own. 16384 is 2^14, so the slot width is an exact power of two and x - lo
is an exact f32 subtraction (Sterbenz) whenever x is in the slot.

The grid is fine enough that a straight line stays within 1 ulp of f64 tanh
cast to f32 on the samples this script checks. The Rust exhaustive sweep is
the lock.
"""
from __future__ import annotations

import hashlib
import struct
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
BIN = ROOT / "crates" / "ferric-core" / "src" / "det_tanh_table.bin"
META = ROOT / "crates" / "ferric-core" / "src" / "det_tanh_table.rs"
W = np.float64(2.0**-14)


def f32(x) -> np.float32:
    return np.float32(x)


def bits(x: np.float32) -> int:
    return int(struct.unpack("<I", struct.pack("<f", np.float32(x)))[0])


def main() -> None:
    # Smallest f32 at which tanh rounds to 1, found by binary search and
    # checked forward by the exhaustive Rust test.
    lo_b, hi_b = bits(f32(8.0)), bits(f32(12.0))
    while lo_b + 1 < hi_b:
        mid = (lo_b + hi_b) // 2
        if f32(np.tanh(np.float64(f32(struct.unpack("<f", struct.pack("<I", mid))[0])))) == f32(1.0):
            hi_b = mid
        else:
            lo_b = mid
    sat = f32(struct.unpack("<f", struct.pack("<I", hi_b))[0])
    n = int(np.floor(float(sat) / float(W))) + 1
    anchor = np.empty(n, dtype=np.float32)
    slope = np.empty(n, dtype=np.float32)
    for i in range(n):
        left = i * float(W)
        right = left + float(W)
        anchor[i] = f32(np.tanh(left))
        slope[i] = f32((np.tanh(right) - np.tanh(left)) / float(W))
    raw = np.empty(n * 2, dtype=np.float32)
    raw[0::2] = anchor
    raw[1::2] = slope
    body = raw.tobytes()
    digest = hashlib.sha256(body).hexdigest()
    if "--check" in sys.argv:
        committed = BIN.read_bytes()
        if committed != body:
            print(f"mismatch sha256 {digest} bytes {len(body)}", file=sys.stderr)
            sys.exit(1)
        print(digest)
        return
    BIN.write_bytes(body)
    META.write_text(
        "\n".join(
            [
                "// Generated by scripts/fit_det_tanh.py. Do not edit by hand.",
                "/// Slot width is 2^-14. `SCALE` is 2^14.",
                f"pub const N: u32 = {n};",
                f"pub const SAT_BITS: u32 = {bits(sat)};",
                "pub const W_BITS: u32 = 0x3880_0000;",
                "pub const SCALE_BITS: u32 = 0x4680_0000;",
                "",
            ]
        )
    )
    print(f"sat {float(sat):.8e} bits {bits(sat):#x} slots {n} bytes {BIN.stat().st_size}")


if __name__ == "__main__":
    main()
